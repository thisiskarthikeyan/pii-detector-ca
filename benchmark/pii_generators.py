"""Generators for checksum-valid Canadian identifiers and plausible PII values.

Identifier values are built with the reference checksums in
``checksums_ref.py`` (not the package's validators) so that the benchmark is
not generated by the code under test. Each identifier is rendered in one of
several surface forms, chosen at random and recorded on the gold entity as
``form`` so recall can be reported per rendering. Some forms are known to be
outside what the recognizers match (lowercase RAMQ letters, lowercase OHIP
version codes); they are included at a low rate precisely so that the
benchmark reports the miss instead of hiding it.

All values are synthetic; checksum validity does not imply the identifier
was ever issued to a real person.
"""

