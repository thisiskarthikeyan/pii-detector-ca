# --- Surface rendering -----------------------------------------------------

# (form name, separator) for grouped digit identifiers, with sampling weights.
# dot / slash are transcription artefacts; "mixed" uses two different
# separators in one value.
_DIGIT_FORMS = [
    ("compact", None, 20),
    ("space", " ", 25),
    ("dash", "-", 25),
    ("dot", ".", 10),
    ("slash", "/", 5),
    ("mixed", "mixed", 5),
]


def _group(digits: str, groups: list[int], sep: str | None) -> str:
    if sep is None:
        return digits
    parts, i = [], 0
    for g in groups:
        parts.append(digits[i : i + g])
        i += g
    if sep == "mixed":
        seps = ["-", " "]
        out = parts[0]
        for k, part in enumerate(parts[1:]):
            out += seps[k % 2] + part
        return out
    return sep.join(parts)


def render_digits(digits: str, groups: list[int], rng: random.Random) -> tuple[str, str]:
    """Render a digit string in a weighted-random surface form: (surface, form)."""
    names, seps, weights = zip(*_DIGIT_FORMS, strict=True)
    idx = rng.choices(range(len(names)), weights=weights, k=1)[0]
    return _group(digits, groups, seps[idx]), names[idx]


# --- Canadian identifiers ----------------------------------------------------


def raw_ca_sin(rng: random.Random) -> str:
    # Leading digits 0 and 8 are not issued.
    base = rng.choice("12345679") + "".join(rng.choices("0123456789", k=7))
    return luhn_append(base)


def raw_ca_ohip(rng: random.Random) -> str:
    # MOH HCV schema: [1-9]\d{9}.
    base = rng.choice("123456789") + "".join(rng.choices("0123456789", k=8))
    return luhn_append(base)


def raw_ca_bc_phn(rng: random.Random) -> str:
    while True:
        base = "9" + "".join(rng.choices("0123456789", k=8))
        check = bc_phn_check(base)
        if check is not None:
            return base + str(check)


def raw_ca_ab_uli(rng: random.Random) -> str:
    digits = "".join(rng.choices("0123456789", k=9))
    if len(set(digits)) == 1:
        digits = digits[:-1] + str((int(digits[-1]) + 1) % 10)
    return digits


def _ramq_letters(last: str, first: str) -> str:
    """RAMQ NAM letter block: 3 letters of the surname at birth + first-name
    initial (per RAMQ's published composition). Apostrophes/hyphens are
    dropped; surnames shorter than 3 letters are X-padded (synthetic
    convention — RAMQ does not document the short-name rule publicly)."""
    surname = "".join(c for c in last if c.isalpha())[:3].ljust(3, "X")
    return (surname + first[0]).upper()


def raw_ca_ramq(
    rng: random.Random, surname: str | None = None, first_name: str | None = None
) -> str:
    last = surname if surname is not None else rng.choice(CANADIAN_LAST)
    first = first_name if first_name is not None else gen_ca_first_name(rng)
    letters = _ramq_letters(last, first)
    yy = f"{rng.randint(1930, 2015) % 100:02d}"
    # Month of birth, +50 for women (RAMQ sex-offset encoding).
    month = rng.randint(1, 12) + rng.choice([0, 50])
    dd = f"{rng.randint(1, 28):02d}"
    # Final two digits: RAMQ administrative code.
    seq = f"{rng.randint(1, 99):02d}"
    return f"{letters}{yy}{month:02d}{dd}{seq}"


# Other provinces / territories without a dedicated recognizer: (digits,
# grouping, label variants). Formats are the publicly stated lengths; none
# of these jurisdictions publishes a checksum, so values are random digits.
OTHER_PROVINCE_CARDS = {
    "SK": (9, [3, 3, 3], ["Saskatchewan HSN:", "Health services number (SK):"]),
    "MB": (9, [3, 3, 3], ["Manitoba PHIN:", "PHIN:"]),
    "NS": (10, [4, 3, 3], ["Nova Scotia health card:", "NS HCN:"]),
    "NB": (9, [3, 3, 3], ["NB Medicare number:", "Medicare #:"]),
    "NL": (12, [4, 4, 4], ["MCP number:", "NL health card (MCP):"]),
    "PE": (8, [4, 4], ["PEI health card:", "Health card (PE):"]),
}


def render_ca_sin(rng: random.Random) -> tuple[str, str]:
    return render_digits(raw_ca_sin(rng), [3, 3, 3], rng)


def render_ca_ohip(rng: random.Random) -> tuple[str, str]:
    """OHIP number with a version-code rendering appended to the form tag.

    Version-code modes: none; separated uppercase (" KD" / "-KD"); glued
    uppercase ("...897KD"); lowercase (" kd", outside the recognizer's
    case-sensitive match by design, kept at a low rate so the miss is
    reported).
    """
    digits = raw_ca_ohip(rng)
    surface, form = render_digits(digits, [4, 3, 3], rng)
    mode = rng.choices(
        ["none", "separated", "glued", "lowercase"], weights=[35, 45, 12, 8], k=1
    )[0]
    version = rng.choice(["AB", "KD", "JX", "MC", "YD"])
    if mode == "none":
        return surface, form
    if mode == "separated":
        sep = "-" if "-" in surface else " "
        return f"{surface}{sep}{version}", f"{form}+version_sep"
    if mode == "glued":
        return f"{surface}{version}", f"{form}+version_glued"
    return f"{surface} {version.lower()}", f"{form}+version_lower"


def render_ca_bc_phn(rng: random.Random) -> tuple[str, str]:
    return render_digits(raw_ca_bc_phn(rng), [4, 3, 3], rng)


def render_ca_ab_uli(rng: random.Random) -> tuple[str, str]:
    return render_digits(raw_ca_ab_uli(rng), [5, 4], rng)


def render_ca_ramq(
    rng: random.Random, surname: str | None = None, first_name: str | None = None
) -> tuple[str, str]:
    raw = raw_ca_ramq(rng, surname, first_name)
    letters, digits = raw[:4], raw[4:]
    form = rng.choices(
        ["compact", "space", "dash", "lowercase"], weights=[40, 40, 12, 8], k=1
    )[0]
    if form == "compact":
        return raw, form
    if form == "space":
        return f"{letters} {digits[:4]} {digits[4:]}", form
    if form == "dash":
        return f"{letters}-{digits[:4]}-{digits[4:]}", form
    return f"{letters.lower()} {digits[:4]} {digits[4:]}", form


def render_other_province_card(rng: random.Random) -> tuple[str, str, str]:
    """(surface, form, label) for a province without a dedicated recognizer."""
    prov = rng.choice(list(OTHER_PROVINCE_CARDS))
    n_digits, groups, labels = OTHER_PROVINCE_CARDS[prov]
    digits = "".join(rng.choices("0123456789", k=n_digits))
    surface, form = render_digits(digits, groups, rng)
    return surface, f"{prov}:{form}", rng.choice(labels)


def gen_ca_postal(rng: random.Random) -> str:
    first = rng.choice("ABCEGHJKLMNPRSTVXY")
    letters = "ABCEGHJKLMNPRSTVWXYZ"
    code = (
        first + str(rng.randint(0, 9)) + rng.choice(letters)
        + str(rng.randint(0, 9)) + rng.choice(letters) + str(rng.randint(0, 9))
    )
    return code[:3] + " " + code[3:]


def render_ca_postal(rng: random.Random) -> tuple[str, str]:
    code = gen_ca_postal(rng)
    form = rng.choices(["space", "compact", "lowercase"], weights=[70, 20, 10], k=1)[0]
    if form == "compact":
        return code.replace(" ", ""), form
    if form == "lowercase":
        return code.lower(), form
    return code, form


